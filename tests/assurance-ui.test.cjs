const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM,VirtualConsole}=require('jsdom');
const base='http://127.0.0.1:8601';
const env=fs.readFileSync('.env','utf8');
const line=env.split('\n').find(x=>x.startsWith('COMPASS_TEST_TOKENS='));
let value=line.slice(line.indexOf('=')+1).trim();
if(value.startsWith("'"))value=value.slice(1,-1).replace(/\\'/g,"'");
const tokens=JSON.parse(value), token=Object.keys(tokens).find(k=>tokens[k]==='ACT-001');
let cookie='';const errors=[];
const vc=new VirtualConsole();vc.on('jsdomError',e=>{if(!e.message.includes('Could not parse CSS')&&!e.message.includes('navigation'))errors.push(e.message)});
const wait=async f=>{for(let i=0;i<200;i++){if(f())return;await new Promise(r=>setTimeout(r,50))}throw Error('UI timeout')};
(async()=>{
 const dom=await JSDOM.fromURL(base,{resources:'usable',runScripts:'dangerously',pretendToBeVisual:true,virtualConsole:vc,beforeParse(w){w.scrollTo=()=>{};w.fetch=async(url,opts={})=>{const headers={...(opts.headers||{})};if(cookie)headers.Cookie=cookie;const r=await fetch(new URL(url,base),{...opts,headers});const c=r.headers.get('set-cookie');if(c)cookie=c.split(';')[0];return r};}});
 const w=dom.window,d=w.document;
 await wait(()=>d.querySelector('#sessionToken'));console.log('Stage: sign-in form');
 d.querySelector('#sessionToken').value=token;
 d.querySelector('#assuranceLogin').dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
 await wait(()=>d.querySelector('.hero h1'));console.log('Stage: authenticated home');
 assert.equal(d.querySelector('#persona').options.length,1);assert(d.querySelector('#persona').disabled);
 assert.equal(w.eval('W.actor.actor_id'),'ACT-001');
 d.querySelector('nav [data-go="ask"]').click();
 d.querySelector('#question').value='Which tool can I use for coding?';
 d.querySelector('#askForm').dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
 await wait(()=>d.querySelector('[data-evidence]'));console.log('Stage: guidance evidence');
 assert(d.querySelector('.answer').textContent.includes('Policy evidence'));
 assert.deepEqual(errors,[]);
 d.querySelector('#signOut').click();
 await wait(()=>cookie==='compass_session='||cookie==='compass_session=""');
 console.log('Stage: signed out');const result=await w.fetch('/api/session');assert.equal(result.status,401);
 console.log('PASS: protected sign-in, fixed actor, disabled persona selector, guidance and citations, sign-out; no application JavaScript errors.');
 dom.window.close();
})().catch(e=>{console.error(e.message);process.exit(1)});
